"""DOCX в оформлении существующих отчётов кафедры; рисунки из реальных запусков."""

from pathlib import Path
import platform
import sys

from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_LINE_SPACING
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Cm, Pt

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT.parent / "scripts"))
from report_builder import (LabMeta, add_heading, add_image, add_listing, add_page_break,
                            add_para, add_table_simple, add_title_page, make_doc, save)

SCREENS = ROOT / "report_assets/screenshots"
OUTPUT = ROOT.parent / "docs/reports/lab_05/Ковалев Д.П. ВКБ43 5 лаба.docx"


def main():
    doc = make_doc()
    section = doc.sections[0]
    section.page_width, section.page_height = Cm(21), Cm(29.7)
    doc.core_properties.title = "Лабораторная работа №5. Отладка с помощью logging"
    doc.core_properties.author = "Ковалев Данил Петрович"
    doc.core_properties.subject = "Методы тестирования и отладки программного обеспечения"
    add_title_page(doc, LabMeta(5, "Отладка программы путём трассировки с использованием logging"))
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.paragraph_format.first_line_indent = Cm(0)
    field = OxmlElement("w:fldSimple")
    field.set(qn("w:instr"), "PAGE")
    footer._p.append(field)

    def page(title):
        add_page_break(doc)
        add_heading(doc, title)

    def para(text):
        add_para(doc, text)

    def image(name, caption, width=15.5):
        add_image(doc, SCREENS / (name + ".png"), caption, width_cm=width)
        doc.paragraphs[-2].paragraph_format.keep_with_next = True
        doc.paragraphs[-1].paragraph_format.keep_together = True

    def table(rows, caption):
        add_table_simple(doc, rows, caption=caption)
        t = doc.tables[-1]
        for row in t.rows:
            props = row._tr.get_or_add_trPr()
            props.append(OxmlElement("w:cantSplit"))
        header = OxmlElement("w:tblHeader")
        t.rows[0]._tr.get_or_add_trPr().append(header)

    page("1. Тема, цель и постановка задачи")
    para("Тема работы: отладка Python-программы путём трассировки с использованием стандартного модуля logging.")
    para("Цель: воспроизвести вычислительную ошибку, локализовать её по промежуточным значениям в журнале, исправить причину и подтвердить результат повторным запуском и регрессионными тестами.")
    para("По заданию допускается любой небольшой проект с ошибкой. Для работы подготовлен учебный CLI расчёта заказа; дефект потери дробной части намеренно внесён в исходную версию legacy.py. Исправленный расчёт находится в order.py. Внешние сервисы и персональные данные не используются.")
    add_heading(doc, "Исходные данные и ожидаемый результат", level=2)
    table([
        ["Позиция", "Цена, ₽", "Количество", "Стоимость, ₽"],
        ["Keyboard", "1200,00", "2", "2400,00"],
        ["Mouse", "1600,00", "1", "1600,00"],
        ["Сумма товаров", "—", "3 шт.", "4000,00"],
    ], "Таблица 1 — заказ LAB5-001 из data/order.json")
    para("Скидка — 10%. Контрольный расчёт вручную: 4000 × (1 − 10 / 100) = 3600,00 ₽. Сумма скидки — 400,00 ₽. Значение expected_total хранится в JSON отдельно и используется только для проверки, а не при вычислении результата.")
    para(f"Среда выполнения: macOS, Python {platform.python_version()}; зависимости зафиксированы в uv.lock. Расчёты выполняются с Decimal; окончательная сумма округляется до копеек по правилу ROUND_HALF_UP.")

    page("2. Воспроизведение ошибки")
    para("Сначала исходная версия запущена с уровнем INFO и ключом --check. Проверка сравнивает вычисленную сумму с независимым контрольным значением из входного файла.")
    image("01_reproduce", "Рисунок 1 — исходная версия возвращает 4000,00 ₽ вместо 3600,00 ₽")
    para("Получен воспроизводимый дефект: программа завершается без исключения в расчёте, но результат завышен на 400,00 ₽. Сообщение ERROR относится к провалу контрольного сравнения; код завершения 1 задаётся ключом --check.")
    table([
        ["Гипотеза", "Как проверить по журналу"],
        ["1. Теряется дробная часть коэффициента", "Вывести процент и коэффициент: ожидается 10 → 0.1."],
        ["2. Неверно складываются стоимости позиций", "Сопоставить line_total и subtotal с ручным расчётом."],
        ["3. Скидка не вычитается из суммы", "Сопоставить discount_amount и total."],
    ], "Таблица 2 — гипотезы перед анализом трассировки")
    para("Уровень INFO фиксирует итог и исходный процент, но не показывает место искажения. Для различения гипотез включён DEBUG.")

    page("3. Настройка журнала и точек трассировки")
    para("Конфигурация logging задаётся один раз в CLI. StreamHandler направляет записи в stderr; FileHandler сохраняет тот же поток в UTF-8. Уровень выбирается аргументом --log-level. Формат содержит время, уровень, имя логгера и сообщение [1].")
    image("09_logging", "Рисунок 2 — фактическая конфигурация стандартного logging в __main__.py")
    table([
        ["Уровень", "Применение в работе"],
        ["DEBUG", "Стоимость каждой позиции, subtotal, rate, discount_amount, total."],
        ["INFO", "Выбранная версия, номер заказа, скидка и успешная проверка."],
        ["ERROR", "Несовпадение с эталоном; ошибка входных данных с traceback."],
    ], "Таблица 3 — назначение используемых уровней")
    para("Точки трассировки выбраны на границах вычислений: чтение скидки → сумма позиций → коэффициент → размер скидки → итог. Значения передаются через параметры logger.debug, поэтому код вычислений не подменяется диагностикой.")

    page("4. Анализ трассировки исходной версии")
    para("Тот же заказ повторно обработан с --log-level DEBUG. Полный журнал дополнительно записан в report_assets/logs/legacy.log; данные и контрольная сумма не изменялись.")
    image("02_trace_legacy", "Рисунок 3 — трассировка локализует ошибку при вычислении rate")
    table([
        ["Наблюдение в журнале", "Вывод"],
        ["line_total=2400.00 и 1600.00", "Цена и количество обработаны верно."],
        ["subtotal=4000.00", "Гипотеза 2 не подтверждена."],
        ["discount_percent=10 rate=0", "Первое неверное значение: коэффициент скидки."],
        ["discount_amount=0.00 total=4000.00", "Вычитание верно для ошибочно нулевой скидки; гипотеза 3 не подтверждена."],
    ], "Таблица 4 — связь наблюдений с выводами")
    para("Подтвердилась гипотеза 1: данные и промежуточная сумма корректны, а ошибка появляется при переводе процентов в долю единицы. Дальнейший расчёт лишь распространяет уже искажённое значение.")

    page("5. Причина и исправление дефекта")
    para("В исходном выражении деление 10 / 100 даёт Decimal('0.1'), после чего int(...) отбрасывает дробную часть и возвращает 0. Обратное преобразование в Decimal уже не восстанавливает потерянную точность. Для любой скидки строго между 0% и 100% коэффициент становится нулевым.")
    image("08_fix", "Рисунок 4 — исправление одной строки: удалено преобразование через int")
    para("Исправление сохраняет результат деления как Decimal: rate = discount_percent / Decimal('100'). Для исходного заказа rate = 0.1, discount_amount = 400.00 и total = 3600.00. Decimal выбран для точных десятичных входных значений [2]; переход на двоичный float для исправления не требуется.")
    add_heading(doc, "Почему проверки только крайних значений недостаточно", level=2)
    para("При скидке 0% коэффициент равен 0 в обеих версиях; при 100% — 1 в обеих версиях. Поэтому эти два случая не обнаруживают дефект. Нужны как минимум промежуточная скидка 10% и дробная скидка 0,5%.")
    para("Область изменения ограничена преобразованием процентов в коэффициент. Формула суммы товаров и вычитание скидки оставлены общими для обеих версий. Исходный дефект сохранён в legacy.py, чтобы его можно было повторно продемонстрировать.")

    page("6. Регрессионная проверка до и после")
    para("Тест test_discount_regression проверяет один и тот же заказ и ожидает Decimal('3600.00'). Перед исправлением он завершился ошибкой сравнения 4000.00 и 3600.00. После изменения строки тот же тест проходит.")
    image("03_regression_before", "Рисунок 5 — регрессионный тест обнаруживает ошибку до исправления")
    image("05_regression_after", "Рисунок 6 — тот же тест после исправления проходит")
    para("Для повторной сборки иллюстрации «до» создаётся изолированный снимок исходников в /tmp с прежней строкой вычисления rate. Тесты копируются без изменений. Рабочая исправленная версия при этом не меняется.")

    page("7. Повторный запуск исходного сценария")
    para("Исправленная версия обработала исходный data/order.json с теми же 10% скидки и контрольным значением 3600.00. Журнал сохранён в report_assets/logs/fixed.log.")
    image("04_trace_fixed", "Рисунок 7 — корректная трассировка и успешное контрольное сравнение")
    table([
        ["Показатель", "До исправления", "После исправления"],
        ["subtotal, ₽", "4000,00", "4000,00"],
        ["rate", "0", "0.1"],
        ["discount_amount, ₽", "0,00", "400,00"],
        ["total, ₽", "4000,00", "3600,00"],
        ["Проверка / код завершения", "FAIL / 1", "PASS / 0"],
    ], "Таблица 5 — сравнение одного сценария на двух версиях")
    para("Логи подтвердили не только правильный итог, но и восстановление промежуточных значений. Поэтому результат не является случайным совпадением с контрольной суммой.")

    page("8. Автоматическое тестирование")
    para("Полный набор содержит 19 тестовых случаев: 16 для расчёта и трассировки, 3 для CLI. Все проверки завершились успешно; пропущенных и ожидаемо падающих тестов нет. Проверка legacy отдельно подтверждает сохранение исходного дефекта.")
    image("06_tests", "Рисунок 8 — полный запуск pytest: 19 passed")
    para("Проверены скидки 0%, 0,5%, 10%, 25%, 100%; округление 0.045 → 0.05; отклонение скидок −1%, 101% и NaN, а также недопустимых количеств. Дополнительно проверены промежуточные DEBUG-записи, запись журнала в файл, коды завершения CLI и traceback при отсутствии входного файла.")

    page("9. Выводы и воспроизведение")
    para("Выполнена отладка учебного Python-проекта с помощью стандартного logging. Ошибка проявлялась неверной суммой заказа без исключения. Трассировка позволила установить первое неверное значение — rate=0 после преобразования через int. Удаление этого преобразования восстановило скидку 400,00 ₽ и итог 3600,00 ₽.")
    para("Повторный запуск исходного сценария и все 19 тестов подтвердили исправление. Для предотвращения повторения дефекта необходимо проверять промежуточные проценты и дробные скидки. Подробные сообщения оставлены на DEBUG; по умолчанию используется INFO.")
    add_heading(doc, "Команды из каталога лабораторной №5", level=2)
    add_listing(doc,
        "uv sync --all-groups\n"
        "export PYTHONPATH=src\n"
        "# Воспроизведение дефекта: код завершения 1\n"
        ".venv/bin/python -m fifth_laboratory \\\n"
        "  --version legacy --log-level DEBUG --check\n"
        "# Исправленная версия: код завершения 0\n"
        ".venv/bin/python -m fifth_laboratory \\\n"
        "  --version fixed --log-level DEBUG --check\n"
        ".venv/bin/python -m pytest\n"
        "# Обновление иллюстраций и DOCX\n"
        ".venv/bin/python scripts/capture_evidence.py\n"
        ".venv/bin/python scripts/build_report.py")
    add_heading(doc, "Источники", level=2)
    para("1. Python Software Foundation. logging — Logging facility for Python. https://docs.python.org/3/library/logging.html (дата обращения: 20.10.2026).")
    para("2. Python Software Foundation. decimal — Decimal fixed-point and floating-point arithmetic. https://docs.python.org/3/library/decimal.html (дата обращения: 20.10.2026).")
    para("3. Условие лабораторной работы №5 (README.md); исходники и журналы запусков настоящего проекта.")

    # Единая полоса набора: заголовки не остаются внизу, подписи идут с рисунками.
    for paragraph in doc.paragraphs:
        if paragraph.runs and all(r.bold for r in paragraph.runs) and paragraph.text.strip():
            paragraph.paragraph_format.keep_with_next = True
        paragraph.paragraph_format.widow_control = True
    save(doc, OUTPUT)
    print(OUTPUT)


if __name__ == "__main__":
    main()
